export function getGuideForItem(item) {
  const g = CHECKLIST_GUIDES[item.id] || {};
  return {
    owner: g.owner || (item.level === 'wires' ? 'auto' : 'you'),
    blocksRelease: Boolean(g.blocksRelease),
    scope: g.scope || 'app',
    ctaLabel: g.ctaLabel || (g.owner === 'decision' ? 'Decide' : g.owner === 'auto' ? 'Setup' : 'Fix'),
    consolePath: g.consolePath || null,
    consoleUrl: g.consoleUrl || null,
    cliCommand: g.cliCommand || null,
    requiredSecrets: g.requiredSecrets || [],
    autoAction: g.autoAction || null,
    decision: g.decision || null,
    steps: g.steps || [
      {
        title: item.title,
        detail: item.fix || item.why || 'Complete this check and mark it done once verified.',
      },
    ],
  };
}
